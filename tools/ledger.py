"""Regenerate the send ledger in STATUS.md from sends.tsv (written by tools/okc_send.py at send time,
with the sha256 of the bytes sent) plus each job's saved judge profile (<problem>/runs/profiles/*.<job>.json).
The older table (jobs before sends.tsv existed) is kept as-is under its own heading."""
import csv, glob, json

HEAD = "## Send ledger (generated by tools/ledger.py from sends.tsv; times ET)"
rows = []
with open("sends.tsv") as f:
    for r in csv.DictReader(f, delimiter="\t"):
        res = "pending (profile not saved)"
        prof = glob.glob(f"{r['problem']}/runs/profiles/*.{r['job_id']}.json")
        if prof:
            d = json.load(open(prof[0]))
            s = d.get("summary") or d.get("result") or {}
            if s.get("speedup") is not None:
                lo, hi = s.get("speedup_ci") or (float("nan"), float("nan"))
                res = f"{s['speedup']:.3f}x ({lo:.3f}-{hi:.3f}), passed={s.get('passed')}"
            else:
                res = f"status={s.get('status')} error={str(s.get('error'))[:60]}"
        rows.append((r["time_et"], r["job_id"], r["problem"], r["kind"], r["file"].split("/")[-1],
                     r["sha256"][:16], r["git_commit"], res, (r.get("notes") or "").replace("|", "/")))
table = [HEAD, "", "| time | job | problem | kind | file | sha256[:16] (at send) | commit | judge | notes |",
         "|---|---|---|---|---|---|---|---|---|"] + ["| " + " | ".join(x) + " |" for x in rows]
s = open("STATUS.md").read()
if HEAD in s:
    a = s.index(HEAD)
    b = s.find("\n## ", a + 1)
    s = s[:a] + "\n".join(table) + "\n" + (s[b:] if b >= 0 else "")
else:
    s = s.rstrip() + "\n\n" + "\n".join(table) + "\n"
open("STATUS.md", "w").write(s)
